#!/bin/bash

# Prints the ws client tests as one Rust file (run.sh writes it to
# tests/ws_client.rs). Each test inlines the snippets the way an app's game
# loop would, against a small server the test runs on a thread (threads are
# fine in test code; the snippets themselves use none).

: "${ORC_WS:?set ORC_WS (see run.sh)}"
: "${NSMAP:?set NSMAP (see run.sh)}"

v=mn_
# maps
export ${v}ws_Url=url
export ${v}ws_Ws=ws
export ${v}ws_Text=text
export ${v}rd_Ws=ws
export ${v}rd_Text=received
export ${v}post_Url=url
export ${v}post_Post=post

# between heredocs, not in backticks, so a version mismatch stops generation
TS_V=$(sed -n 's/^ORC_WS_V="\(.*\)"$/\1/p' "${ORC_WS}/version.sh")
TS_MODELS=$("${ORC_WS}/models.sh" "${TS_V}") || exit 1

cat << EOF
// Code generated by unit/ws-client.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]

use std::io::{Read, Write};
use std::net::TcpListener;
use std::time::{Duration, Instant};

${TS_MODELS}

// A websocket server for one client: echoes each text message back, then
// closes with "bye" after the message "close".
fn echo_server() -> String {
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let addr = listener.local_addr().unwrap();
    std::thread::spawn(move || {
        let (stream, _) = listener.accept().unwrap();
        let mut socket = tungstenite::accept(stream).unwrap();
        loop {
            match socket.read() {
                Ok(tungstenite::Message::Text(t)) if t.as_str() == "close" => {
                    let _ = socket.close(Some(tungstenite::protocol::CloseFrame {
                        code: tungstenite::protocol::frame::coding::CloseCode::Normal,
                        reason: "bye".into(),
                    }));
                    let _ = socket.flush();
                    std::thread::sleep(Duration::from_millis(200));
                    return;
                }
                Ok(tungstenite::Message::Text(t)) => socket.send(tungstenite::Message::text(t.as_str())).unwrap(),
                Ok(_) => {}
                Err(_) => return,
            }
        }
    });
    format!("http://{addr}/ws")
}

// An HTTP server for one request, replying with this status line and body.
fn http_server(status: &'static str, body: &'static str) -> String {
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let addr = listener.local_addr().unwrap();
    std::thread::spawn(move || {
        let (mut stream, _) = listener.accept().unwrap();
        let mut buf = [0u8; 1024];
        let _ = stream.read(&mut buf);
        let reply = format!("HTTP/1.1 {status}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}", body.len());
        stream.write_all(reply.as_bytes()).unwrap();
    });
    format!("http://{addr}/match")
}

// polls read.sh, as a game loop would once a frame, until a message arrives
// or the socket closes (or 3 seconds pass)
fn read_until_message(ws: &mut WsClient) -> Option<String> {
    let start = Instant::now();
    let mut received_any: Option<String> = None;
    let mut polling = true;
    while polling {
        ` ${ORC_WS}/snippets/read.sh ${v}rd_ `
        if received.is_some() {
            received_any = received;
        }
        polling = received_any.is_none() && ws.state != 2 && start.elapsed() < Duration::from_secs(3);
        std::thread::sleep(Duration::from_millis(5));
    }
    received_any
}

#[test]
fn connect_send_and_read_an_echo() {
    let url = echo_server();
    ` ${ORC_WS}/snippets/connect.sh ${v}ws_ `
    assert_eq!(ws.state, 1, "not open: {}", ws.close_reason);

    let text = "hello";
    ` ${ORC_WS}/snippets/send.sh ${v}ws_ `
    assert_eq!(read_until_message(&mut ws), Some("hello".to_string()));

    // a second round trip, so reads keep working after the first
    let text = String::from("again");
    ` ${ORC_WS}/snippets/send.sh ${v}ws_ `
    assert_eq!(read_until_message(&mut ws), Some("again".to_string()));
}

#[test]
fn read_without_a_message_returns_none_at_once() {
    let url = echo_server();
    ` ${ORC_WS}/snippets/connect.sh ${v}ws_ `
    let start = Instant::now();
    ` ${ORC_WS}/snippets/read.sh ${v}rd_ `
    assert_eq!(received, None);
    assert!(start.elapsed() < Duration::from_millis(100), "read.sh waited {:?}", start.elapsed());
    assert_eq!(ws.state, 1);
}

#[test]
fn a_server_close_closes_the_client_with_its_reason() {
    let url = echo_server();
    ` ${ORC_WS}/snippets/connect.sh ${v}ws_ `
    let text = "close";
    ` ${ORC_WS}/snippets/send.sh ${v}ws_ `
    assert_eq!(read_until_message(&mut ws), None);
    assert_eq!(ws.state, 2);
    assert_eq!(ws.close_reason, "bye");
}

#[test]
fn connecting_to_nothing_fails_with_a_reason() {
    // bind then drop a listener, so nothing listens on the port
    let port = TcpListener::bind("127.0.0.1:0").unwrap().local_addr().unwrap().port();
    let url = format!("http://127.0.0.1:{port}/ws");
    ` ${ORC_WS}/snippets/connect.sh ${v}ws_ `
    assert_eq!(ws.state, 2);
    assert!(!ws.close_reason.is_empty());
    // sending on a closed client does nothing
    let text = "ignored";
    ` ${ORC_WS}/snippets/send.sh ${v}ws_ `
    assert_eq!(ws.state, 2);
}

#[test]
fn post_returns_the_body_of_a_200() {
    let url = http_server("200 OK", r#"{"match_id":"m1","player":0}"#);
    ` ${ORC_WS}/snippets/post.sh ${v}post_ `
    ` ${ORC_WS}/snippets/post-poll.sh ${v}post_ `
    assert!(post.done);
    assert_eq!(post.body, Ok(r#"{"match_id":"m1","player":0}"#.to_string()));
}

#[test]
fn post_fails_on_another_status() {
    let url = http_server("503 Service Unavailable", "busy");
    ` ${ORC_WS}/snippets/post.sh ${v}post_ `
    ` ${ORC_WS}/snippets/post-poll.sh ${v}post_ `
    assert!(post.done);
    assert_eq!(post.body, Err("server replied HTTP/1.1 503 Service Unavailable".to_string()));
}
