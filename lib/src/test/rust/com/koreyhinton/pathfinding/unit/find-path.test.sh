#!/bin/bash

# Prints the unit tests for the pathfinding library's find-path snippet as
# one Rust file (run.sh writes it to src/lib.rs).
#
# find() inlines the snippet once, the way an app would, and most tests call
# it. Grids are drawn as rows of text: '#' is a blocked cell, anything else
# is open. On random grids, the tests check every path against a plain
# Dijkstra search over the same moves (reference_costs), so a path must be
# the cheapest there is, not just a path.

: "${ORC_PATHFINDING:?set ORC_PATHFINDING (see run.sh)}"
: "${NSMAP:?set NSMAP (see run.sh)}"

# find <ns> <path> <found>: inline find-path, reading grid, start and goal,
# and declaring the path and found variables named
find() {
    export ${1}Grid=grid
    export ${1}Start=start
    export ${1}Goal=goal
    export ${1}Path=${2}
    export ${1}Found=${3}
    "${ORC_PATHFINDING}/snippets/find-path.sh" "${1}"
}

# Ask models.sh for the library's own version. It runs here, not in the
# heredoc's backticks, so a version mismatch stops generation.
TS_V=""
if [[ -f "${ORC_PATHFINDING}/version.sh" ]]; then
    TS_V=$(sed -n 's/^ORC_PATHFINDING_V="\(.*\)"$/\1/p' "${ORC_PATHFINDING}/version.sh")
fi
TS_MODELS=$("${ORC_PATHFINDING}/models.sh" "${TS_V}") || exit 1

cat << EOF
// Code generated by unit/find-path.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]

#[cfg(test)]
mod tests {
${TS_MODELS}

    type Cell = (usize, usize);

    // a grid from rows of text: '#' is blocked
    fn grid_of(rows: &[&str]) -> PathGrid {
        let w = rows[0].len();
        let blocked = rows.iter().flat_map(|row| row.chars().map(|c| c == '#')).collect();
        PathGrid { w, h: rows.len(), blocked }
    }

    // the snippet, inlined once
    fn find(grid: &PathGrid, start: Cell, goal: Cell) -> (Vec<Cell>, bool) {
        $(find mn_t_ path found)
        (path, found)
    }

    fn is_blocked(grid: &PathGrid, cell: Cell) -> bool {
        grid.blocked[cell.1 * grid.w + cell.0]
    }

    // the cost of one step: 10 straight, 14 diagonal. Panics on a step that
    // isn't to a neighbor, onto a blocked cell, or across a blocked corner.
    fn step_cost(grid: &PathGrid, from: Cell, to: Cell) -> u32 {
        let dx = from.0.abs_diff(to.0);
        let dy = from.1.abs_diff(to.1);
        assert!(dx <= 1 && dy <= 1 && dx + dy > 0, "{from:?} to {to:?} isn't a step to a neighbor");
        assert!(!is_blocked(grid, to), "the path steps onto blocked {to:?}");
        if dx + dy == 2 {
            assert!(
                !is_blocked(grid, (to.0, from.1)) && !is_blocked(grid, (from.0, to.1)),
                "{from:?} to {to:?} cuts a blocked corner"
            );
            14
        } else {
            10
        }
    }

    // the cost of walking the path from start, checking every step
    fn walk(grid: &PathGrid, start: Cell, path: &[Cell]) -> u32 {
        let mut at = start;
        let mut total = 0;
        for &cell in path {
            total += step_cost(grid, at, cell);
            at = cell;
        }
        total
    }

    // the octile distance, the snippet's estimate
    fn octile(a: Cell, b: Cell) -> u32 {
        let dx = a.0.abs_diff(b.0) as u32;
        let dy = a.1.abs_diff(b.1) as u32;
        10 * dx.max(dy) + 4 * dx.min(dy)
    }

    // Dijkstra from start over the same moves: the cheapest cost to every
    // cell (u32::MAX where unreachable). Like the snippet, it leaves a
    // blocked start.
    fn reference_costs(grid: &PathGrid, start: Cell) -> Vec<u32> {
        let mut cost = vec![u32::MAX; grid.w * grid.h];
        let mut heap = std::collections::BinaryHeap::new();
        cost[start.1 * grid.w + start.0] = 0;
        heap.push(std::cmp::Reverse((0u32, start)));
        while let Some(std::cmp::Reverse((c, at))) = heap.pop() {
            if c > cost[at.1 * grid.w + at.0] {
                continue;
            }
            for dy in -1i64..=1 {
                for dx in -1i64..=1 {
                    let (nx, ny) = (at.0 as i64 + dx, at.1 as i64 + dy);
                    if (dx, dy) == (0, 0) || nx < 0 || ny < 0 || nx >= grid.w as i64 || ny >= grid.h as i64 {
                        continue;
                    }
                    let next = (nx as usize, ny as usize);
                    let diagonal = dx != 0 && dy != 0;
                    if is_blocked(grid, next)
                        || (diagonal && (is_blocked(grid, (next.0, at.1)) || is_blocked(grid, (at.0, next.1))))
                    {
                        continue;
                    }
                    let nc = c + if diagonal { 14 } else { 10 };
                    if nc < cost[next.1 * grid.w + next.0] {
                        cost[next.1 * grid.w + next.0] = nc;
                        heap.push(std::cmp::Reverse((nc, next)));
                    }
                }
            }
        }
        cost
    }

    // a small random number generator, so the random grids are the same on
    // every run
    struct Lcg(u64);
    impl Lcg {
        fn next(&mut self, below: usize) -> usize {
            self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
            ((self.0 >> 33) % below as u64) as usize
        }
    }

    #[test]
    fn a_straight_path_on_open_ground() {
        let grid = grid_of(&["....."]);
        let (path, found) = find(&grid, (0, 0), (4, 0));
        assert!(found);
        assert_eq!(path, vec![(1, 0), (2, 0), (3, 0), (4, 0)]);
    }

    #[test]
    fn at_the_goal_already_the_path_is_empty() {
        let grid = grid_of(&["...", "..."]);
        let (path, found) = find(&grid, (1, 1), (1, 1));
        assert!(found);
        assert!(path.is_empty());
    }

    #[test]
    fn a_diagonal_path_takes_diagonal_steps() {
        let grid = grid_of(&["....", "....", "....", "...."]);
        let (path, found) = find(&grid, (0, 0), (3, 3));
        assert!(found);
        assert_eq!(path, vec![(1, 1), (2, 2), (3, 3)]);
    }

    #[test]
    fn it_goes_around_a_wall_the_short_way() {
        let grid = grid_of(&[
            "......",
            "..#...",
            "..#...",
            "..#...",
            "..#...",
            "......",
        ]);
        let (path, found) = find(&grid, (0, 2), (5, 2));
        assert!(found);
        assert_eq!(path.last(), Some(&(5, 2)));
        let reference = reference_costs(&grid, (0, 2));
        assert_eq!(walk(&grid, (0, 2), &path), reference[2 * 6 + 5], "not the shortest way round");
    }

    #[test]
    fn a_diagonal_step_doesnt_cut_a_blocked_corner() {
        let grid = grid_of(&[".#", ".."]);
        let (path, found) = find(&grid, (0, 0), (1, 1));
        assert!(found);
        assert_eq!(path, vec![(0, 1), (1, 1)]);

        // blocked on both sides: no way through
        let grid = grid_of(&[".#", "#."]);
        let (path, found) = find(&grid, (0, 0), (1, 1));
        assert!(!found);
        assert!(path.is_empty());
    }

    #[test]
    fn an_unreachable_goal_ends_at_the_nearest_reachable_cell() {
        let grid = grid_of(&[
            "....#...",
            "....#...",
            "....#...",
        ]);
        let (path, found) = find(&grid, (0, 1), (6, 1));
        assert!(!found);
        assert_eq!(path.last(), Some(&(3, 1)));
        walk(&grid, (0, 1), &path);
    }

    #[test]
    fn a_blocked_goal_ends_beside_it() {
        let grid = grid_of(&["....#"]);
        let (path, found) = find(&grid, (0, 0), (4, 0));
        assert!(!found);
        assert_eq!(path, vec![(1, 0), (2, 0), (3, 0)]);
    }

    #[test]
    fn a_blocked_start_still_leads_out() {
        let grid = grid_of(&["#..."]);
        let (path, found) = find(&grid, (0, 0), (3, 0));
        assert!(found);
        assert_eq!(path, vec![(1, 0), (2, 0), (3, 0)]);
    }

    #[test]
    fn cells_off_the_grid_move_to_its_edge() {
        let grid = grid_of(&["....", "....", "...."]);
        let (path, found) = find(&grid, (100, 1), (0, 50));
        assert!(found);
        assert_eq!(path.last(), Some(&(0, 2)));
        assert_eq!(walk(&grid, (3, 1), &path), reference_costs(&grid, (3, 1))[2 * 4]);
    }

    #[test]
    fn an_empty_or_mismatched_grid_finds_nothing() {
        let empty = PathGrid { w: 0, h: 0, blocked: vec![] };
        assert_eq!(find(&empty, (0, 0), (0, 0)), (vec![], false));
        let short = PathGrid { w: 3, h: 3, blocked: vec![false; 2] };
        assert_eq!(find(&short, (0, 0), (2, 2)), (vec![], false));
    }

    #[test]
    fn paths_on_random_grids_are_the_cheapest_there_are() {
        let mut rng = Lcg(7);
        let (w, h) = (14, 10);
        let (mut reached, mut missed) = (0, 0);
        for _ in 0..200 {
            let blocked = (0..w * h).map(|_| rng.next(100) < 30).collect();
            let grid = PathGrid { w, h, blocked };
            let start = (rng.next(w), rng.next(h));
            let goal = (rng.next(w), rng.next(h));
            let reference = reference_costs(&grid, start);
            let (path, found) = find(&grid, start, goal);
            let end = path.last().copied().unwrap_or(start);
            if reference[goal.1 * w + goal.0] != u32::MAX {
                reached += 1;
                assert!(found, "{start:?} to {goal:?} is reachable, but wasn't found");
                assert_eq!(end, goal);
                assert_eq!(walk(&grid, start, &path), reference[goal.1 * w + goal.0], "{start:?} to {goal:?} isn't the cheapest path");
            } else {
                missed += 1;
                assert!(!found, "{start:?} to {goal:?} can't be reached, but was found");
                // the reachable cell nearest the goal, then the cheapest,
                // then the lowest index
                let nearest = (0..w * h)
                    .filter(|&i| reference[i] != u32::MAX)
                    .map(|i| (octile((i % w, i / w), goal), reference[i], i))
                    .min()
                    .unwrap();
                assert_eq!(end, (nearest.2 % w, nearest.2 / w), "{start:?} to {goal:?} didn't end nearest the goal");
                assert_eq!(walk(&grid, start, &path), nearest.1, "{start:?} to {goal:?} isn't the cheapest way to the nearest cell");
            }
        }
        // the grids should cover both cases
        assert!(reached > 50 && missed > 20, "reached {reached}, missed {missed}");
    }

    #[test]
    fn the_same_grid_and_cells_give_the_same_path() {
        let mut rng = Lcg(99);
        let (w, h) = (20, 20);
        let blocked = (0..w * h).map(|_| rng.next(100) < 20).collect();
        let grid = PathGrid { w, h, blocked };
        assert_eq!(find(&grid, (0, 0), (19, 19)), find(&grid, (0, 0), (19, 19)));
    }

    #[test]
    fn two_finds_in_one_scope_dont_clash() {
        let grid = grid_of(&["....", "...."]);
        let start = (0usize, 0usize);
        let goal = (3usize, 0usize);
        $(find mn_a_ path_a found_a)
        let goal = (0usize, 1usize);
        $(find mn_b_ path_b found_b)
        assert!(found_a && found_b);
        assert_eq!(path_a, vec![(1, 0), (2, 0), (3, 0)]);
        assert_eq!(path_b, vec![(0, 1)]);
    }
}
EOF
