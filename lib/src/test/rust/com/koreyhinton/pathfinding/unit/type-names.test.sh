#!/bin/bash

# Prints a test of the pathfinding library's type-name setting as one Rust
# file (run.sh writes it to tests/type_names.rs, its own crate, since a name
# clash fails the whole compile).
#
# It plays an app that already has its own PathGrid type. The app renames the
# library's with the setting, then uses both in one scope. Without the
# setting, models.sh defines the same name again and this doesn't compile
# (E0428).

: "${ORC_PATHFINDING:?set ORC_PATHFINDING (see run.sh)}"
: "${NSMAP:?set NSMAP (see run.sh)}"

# settings: the library's type name, renamed to dodge the app's
export PATHFINDING_GRID_FULLY_QUALIFIED=OrcPathGrid

# maps
export mn_t_Grid=grid
export mn_t_Start=start
export mn_t_Goal=goal
export mn_t_Path=path
export mn_t_Found=found

# Ask models.sh for the library's own version. It runs here, not in the
# heredoc's backticks, so a version mismatch stops generation.
TS_V=""
if [[ -f "${ORC_PATHFINDING}/version.sh" ]]; then
    TS_V=$(sed -n 's/^ORC_PATHFINDING_V="\(.*\)"$/\1/p' "${ORC_PATHFINDING}/version.sh")
fi
TS_MODELS=$("${ORC_PATHFINDING}/models.sh" "${TS_V}") || exit 1

cat << EOF
// Code generated by unit/type-names.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]

// the app's own type, with the name the library uses by default
struct PathGrid {
    label: &'static str,
}

// the library's type, renamed by the setting
${TS_MODELS}

#[test]
fn the_renamed_library_type_lives_beside_the_apps_own() {
    let app_grid = PathGrid { label: "app grid" };
    let grid = OrcPathGrid { w: 3, h: 1, blocked: vec![false; 3] };
    let start = (0usize, 0usize);
    let goal = (2usize, 0usize);

    `"${ORC_PATHFINDING}/snippets/find-path.sh" mn_t_`

    assert!(found);
    assert_eq!(path, vec![(1, 0), (2, 0)]);
    assert_eq!(app_grid.label, "app grid");
}
EOF
