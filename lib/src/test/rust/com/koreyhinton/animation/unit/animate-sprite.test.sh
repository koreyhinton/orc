#!/bin/bash

# Prints the unit tests for the animation library's animate-sprite snippet
# as one Rust file (run.sh writes it to src/lib.rs). Each test inlines the
# snippet where an app would: once per update, after adding frame time.
#
# Every test uses tiles 32 wide and 48 tall, so x, y, w and h can't be
# mixed up, and adds 0.03s per update to 10 fps animations: 3 updates
# (0.09s) don't reach the 0.1s interval, and the 4th (0.12s) steps.

: "${ORC_ANIMATION:?set ORC_ANIMATION (see run.sh)}"
: "${NSMAP:?set NSMAP (see run.sh)}"

# update <ns> <sprite>: inline animate-sprite for one sprite variable
update() {
    export ${1}AnimatedSprite=${2}
    "${ORC_ANIMATION}/snippets/macroquad/animate-sprite.sh" "${1}"
}

# Ask models.sh for the library's own version. It runs here, not in the
# heredoc's backticks, so a version mismatch stops generation.
TS_V=""
if [[ -f "${ORC_ANIMATION}/version.sh" ]]; then
    TS_V=$(sed -n 's/^ORC_ANIMATION_V="\(.*\)"$/\1/p' "${ORC_ANIMATION}/version.sh")
fi
TS_MODELS=$("${ORC_ANIMATION}/models.sh" "${TS_V}") || exit 1

cat << EOF
// Code generated by unit/animate-sprite.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]

#[cfg(test)]
mod tests {
${TS_MODELS}

    fn walk() -> Animation {
        Animation { id: "walk".into(), fps: 10.0, frames: 6, row: 1 }
    }

    fn idle() -> Animation {
        Animation { id: "idle".into(), fps: 10.0, frames: 2, row: 0 }
    }

    fn new_sprite(animation: &Animation) -> AnimatedSprite<'_> {
        AnimatedSprite {
            w: 32.0,
            h: 48.0,
            frame: 0,
            frame_time: 0.0,
            animation,
            last_animation_id: String::new(),
            paint_frame: None,
        }
    }

    fn paint(sprite: &AnimatedSprite) -> (f32, f32, f32, f32) {
        let pf = sprite.paint_frame.as_ref().expect("paint_frame not set");
        (pf.x, pf.y, pf.w, pf.h)
    }

    #[test]
    fn first_update_starts_at_frame_0_on_the_animation_row() {
        let walk = walk();
        let mut sprite = new_sprite(&walk);
        sprite.frame = 3;
        sprite.frame_time = 0.5;

        $(update mn_t_ sprite)

        assert_eq!(sprite.frame, 0);
        assert_eq!(sprite.frame_time, 0.0);
        assert_eq!(sprite.last_animation_id, "walk");
        assert_eq!(paint(&sprite), (0.0, 48.0, 32.0, 48.0));
    }

    #[test]
    fn first_update_restarts_even_if_last_id_already_matches() {
        let walk = walk();
        let mut sprite = new_sprite(&walk);
        sprite.last_animation_id = "walk".into();
        sprite.frame = 3;
        sprite.frame_time = 0.5;

        $(update mn_t_ sprite)

        assert_eq!(sprite.frame, 0);
        assert_eq!(sprite.frame_time, 0.0);
        assert_eq!(paint(&sprite), (0.0, 48.0, 32.0, 48.0));
    }

    #[test]
    fn steps_only_once_the_interval_has_passed() {
        let walk = walk();
        let mut sprite = new_sprite(&walk);
        $(update mn_t_ sprite)

        for _ in 0..3 {
            sprite.frame_time += 0.03;
            $(update mn_t_ sprite)
        }
        assert_eq!(sprite.frame, 0, "stepped before 0.1s");

        sprite.frame_time += 0.03;
        $(update mn_t_ sprite)

        assert_eq!(sprite.frame, 1);
        assert_eq!(sprite.frame_time, 0.0);
        assert_eq!(paint(&sprite), (32.0, 48.0, 32.0, 48.0));
    }

    #[test]
    fn wraps_to_frame_0_after_the_last_frame() {
        let walk = walk();
        let mut sprite = new_sprite(&walk);
        $(update mn_t_ sprite)

        let mut frames = Vec::new();
        for _ in 0..7 {
            sprite.frame_time += 0.2;
            $(update mn_t_ sprite)
            frames.push(sprite.frame);
        }

        assert_eq!(frames, vec![1, 2, 3, 4, 5, 0, 1]);
    }

    #[test]
    fn swap_restarts_at_frame_0_on_the_new_row() {
        let walk = walk();
        let idle = idle();
        let mut sprite = new_sprite(&walk);
        $(update mn_t_ sprite)
        sprite.frame = 4;

        // past the interval too: the swap wins, so no step this update
        sprite.animation = &idle;
        sprite.frame_time += 0.2;
        $(update mn_t_ sprite)

        assert_eq!(sprite.frame, 0);
        assert_eq!(sprite.frame_time, 0.0);
        assert_eq!(sprite.last_animation_id, "idle");
        assert_eq!(paint(&sprite), (0.0, 0.0, 32.0, 48.0));
    }

    #[test]
    fn swap_to_fewer_frames_stays_inside_the_new_animation() {
        let walk = walk();
        let idle = idle();
        let mut sprite = new_sprite(&walk);
        $(update mn_t_ sprite)
        sprite.frame = 5;

        sprite.animation = &idle;
        for _ in 0..5 {
            sprite.frame_time += 0.2;
            $(update mn_t_ sprite)
            assert!(sprite.frame < idle.frames, "frame {} of {}", sprite.frame, idle.frames);
        }
    }

    #[test]
    fn zero_frames_stays_on_frame_0_without_panicking() {
        let empty = Animation { id: "empty".into(), fps: 10.0, frames: 0, row: 2 };
        let mut sprite = new_sprite(&empty);
        for _ in 0..3 {
            sprite.frame_time += 0.2;
            $(update mn_t_ sprite)
        }

        assert_eq!(sprite.frame, 0);
        assert_eq!(paint(&sprite), (0.0, 96.0, 32.0, 48.0));
    }

    #[test]
    fn two_sprites_in_one_scope_and_namespace_stay_separate() {
        let walk = walk();
        let idle = idle();
        let mut hero = new_sprite(&walk);
        let mut villager = new_sprite(&idle);

        $(update mn_t_ hero)
        $(update mn_t_ villager)
        hero.frame_time += 0.2;
        $(update mn_t_ hero)
        $(update mn_t_ villager)

        assert_eq!(hero.frame, 1);
        assert_eq!(villager.frame, 0);
        assert_eq!(paint(&hero), (32.0, 48.0, 32.0, 48.0));
        assert_eq!(paint(&villager), (0.0, 0.0, 32.0, 48.0));
    }

    // An app with many units maps the sprite to an element, not a variable.
    // The snippet must not hold a borrow of one field while it writes
    // another, or indexing borrows the whole Vec twice (E0499) and this
    // file doesn't compile.
    #[test]
    fn works_on_an_indexed_sprite() {
        let walk = walk();
        let idle = idle();
        let mut sprites = vec![new_sprite(&walk), new_sprite(&idle)];

        for i in 0..sprites.len() {
            $(update mn_t_ 'sprites[i]')
        }
        sprites[0].frame_time += 0.2;
        for i in 0..sprites.len() {
            $(update mn_t_ 'sprites[i]')
        }

        assert_eq!(sprites[0].frame, 1);
        assert_eq!(sprites[1].frame, 0);
        assert_eq!(paint(&sprites[0]), (32.0, 48.0, 32.0, 48.0));
        assert_eq!(paint(&sprites[1]), (0.0, 0.0, 32.0, 48.0));
    }
}
EOF
