#!/bin/bash

# Prints a test of the animation library's type-name settings as one Rust
# file (run.sh writes it to tests/type_names.rs, its own crate, since a name
# clash fails the whole compile).
#
# It plays an app that already has its own Animation, AnimatedSprite and
# PaintFrame types (as an app using macroquad's experimental animation module
# would). The app renames the library's types with the settings, then uses
# both its own types and the library's in one scope. Without the settings,
# models.sh defines the same names again and this doesn't compile (E0428).

: "${ORC_ANIMATION:?set ORC_ANIMATION (see run.sh)}"
: "${NSMAP:?set NSMAP (see run.sh)}"

# settings: the library's type names, renamed to dodge the app's
export ANIMATION_ANIMATION_FULLY_QUALIFIED=OrcAnimation
export ANIMATION_ANIMATED_SPRITE_FULLY_QUALIFIED=OrcAnimatedSprite
export ANIMATION_PAINT_FRAME_FULLY_QUALIFIED=OrcPaintFrame

# maps
export mn_t_AnimatedSprite=sprite

# Ask models.sh for the library's own version. It runs here, not in the
# heredoc's backticks, so a version mismatch stops generation.
TS_V=""
if [[ -f "${ORC_ANIMATION}/version.sh" ]]; then
    TS_V=$(sed -n 's/^ORC_ANIMATION_V="\(.*\)"$/\1/p' "${ORC_ANIMATION}/version.sh")
fi
TS_MODELS=$("${ORC_ANIMATION}/models.sh" "${TS_V}") || exit 1

cat << EOF
// Code generated by unit/type-names.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]

// the app's own types, with the names the library uses by default
struct Animation {
    name: &'static str,
}

struct AnimatedSprite {
    animation: Animation,
}

struct PaintFrame {
    label: &'static str,
}

// the library's types, renamed by the settings
${TS_MODELS}

#[test]
fn renamed_library_types_live_beside_the_apps_own() {
    let app_sprite = AnimatedSprite { animation: Animation { name: "app walk" } };
    let app_frame = PaintFrame { label: "app frame" };

    let walk = OrcAnimation { id: "walk".into(), fps: 10.0, frames: 6, row: 1 };
    let mut sprite = OrcAnimatedSprite {
        w: 32.0,
        h: 48.0,
        frame: 0,
        frame_time: 0.0,
        animation: &walk,
        last_animation_id: String::new(),
        paint_frame: None,
    };

    `"${ORC_ANIMATION}/snippets/macroquad/animate-sprite.sh" mn_t_`

    let paint: &OrcPaintFrame = sprite.paint_frame.as_ref().expect("paint_frame not set");
    assert_eq!((paint.x, paint.y, paint.w, paint.h), (0.0, 48.0, 32.0, 48.0));
    assert_eq!(app_sprite.animation.name, "app walk");
    assert_eq!(app_frame.label, "app frame");
}
EOF
